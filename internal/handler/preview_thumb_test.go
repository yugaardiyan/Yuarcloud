func testThumbStore(t *testing.T) (storage.StorageBackend, string) {
	t.Helper()
	root := t.TempDir()
	store, err := storage.NewLocalStorage(&config.Config{
		Storage: config.StorageConfig{
			Type:    "local",
			Local:   config.LocalConfig{Root: root},
			Chunked: config.ChunkedConfig{TempDir: filepath.Join(root, ".yuarcloud-chunks")},
		},
	})
	if err != nil {
		t.Fatalf("storage: %v", err)
	}
	return store, root
}

func writeTestJPEG(t *testing.T, dir, name string, w, h int) (int64, string) {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.Set(x, y, color.RGBA{uint8(x % 256), uint8(y % 256), 64, 255})
		}
	}
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, img, nil); err != nil {
		t.Fatalf("encode: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, name), buf.Bytes(), 0o644); err != nil {
		t.Fatalf("write: %v", err)
	}
	return int64(buf.Len()), name
}

// A ?w= request is answered with a downscaled JPEG and the generation lands in
// the cache so the next request is a file read.
func TestThumbServiceRendersAndCaches(t *testing.T) {
	store, root := testThumbStore(t)
	size, path := writeTestJPEG(t, root, "photo.jpg", 800, 600)

	svc, err := NewThumbService(store, filepath.Join(root, ".yuarcloud-previews"))
	if err != nil {
		t.Fatalf("NewThumbService: %v", err)
	}
	if svc == nil {
		t.Fatal("NewThumbService returned nil for a valid cache dir")
	}

	file := &model.File{
		Name:      "photo.jpg",
		Path:      path,
		Size:      size,
		MimeType:  "image/jpeg",
		UpdatedAt: time.Now(),
	}

	serve := func() *httptest.ResponseRecorder {
		gin.SetMode(gin.TestMode)
		w := httptest.NewRecorder()
		c, _ := gin.CreateTestContext(w)
		c.Request = httptest.NewRequest(http.MethodGet, "/preview?w=64", nil)
		if !svc.ServeThumb(c, file, 64, true) {
			t.Fatal("ServeThumb reported it did not handle the request")
		}
		return w
	}

	first := serve()
	if first.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200", first.Code)
	}
	if ct := first.Header().Get("Content-Type"); ct != "image/jpeg" {
		t.Fatalf("Content-Type = %q, want image/jpeg", ct)
	}
	if cc := first.Header().Get("Cache-Control"); cc == "" {
		t.Fatal("a cacheable preview must carry Cache-Control")
	}
	cfg, _, err := image.DecodeConfig(bytes.NewReader(first.Body.Bytes()))
	if err != nil {
		t.Fatalf("decode preview: %v", err)
	}
	if cfg.Width > 64 || cfg.Height > 64 {
		t.Fatalf("preview is %dx%d, want both <= 64", cfg.Width, cfg.Height)
	}

	// The generated bytes are on disk and a second call serves the same thing.
	cached := filepath.Join(root, ".yuarcloud-previews", file.ID.String())
	entries, err := os.ReadDir(cached)
	if err != nil || len(entries) == 0 {
		t.Fatalf("nothing was cached under %s (err=%v)", cached, err)
	}
	second := serve()
	if !bytes.Equal(first.Body.Bytes(), second.Body.Bytes()) {
		t.Fatal("the cached preview differs from the generated one")
	}
}

// A file type the renderer cannot handle is left to serveInline.
func TestThumbServiceDeclinesUnsupported(t *testing.T) {
	store, root := testThumbStore(t)
	svc, err := NewThumbService(store, filepath.Join(root, ".yuarcloud-previews"))
	if err != nil {
		t.Fatalf("NewThumbService: %v", err)
	}

	gin.SetMode(gin.TestMode)
	w := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(w)
	c.Request = httptest.NewRequest(http.MethodGet, "/preview?w=64", nil)

	if svc.ServeThumb(c, &model.File{Name: "clip.mp4", MimeType: "video/mp4"}, 64, true) {
		t.Fatal("ServeThumb handled a video, want declined")
	}
	if svc.ServeThumb(c, &model.File{Name: "a.jpg", MimeType: "image/jpeg"}, 0, true) {
		t.Fatal("ServeThumb handled a zero width, want declined")
	}
	if svc.ServeThumb(c, &model.File{Name: "a.jpg", MimeType: "image/jpeg"}, 999999, true) {
		t.Fatal("ServeThumb handled an out-of-range width, want declined")
	}
	// A nil service is the "feature off" state and must not panic.
	var nilSvc *ThumbService
	if nilSvc.ServeThumb(c, &model.File{Name: "a.jpg", MimeType: "image/jpeg"}, 64, true) {
		t.Fatal("nil ThumbService handled a request")
	}
}
